-- 2. KRIJIMI I STRUKTURES
CREATE TABLE Shitjet (
    id_shitje NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produkti VARCHAR2(100) NOT NULL,
    shuma NUMBER(10, 2) NOT NULL,
    data_sh TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    perdoruesi VARCHAR2(50)
);

CREATE TABLE Audit_Log (
    id_log NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesazhi VARCHAR2(255),
    koha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

