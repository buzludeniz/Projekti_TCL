-- 4. LOGJIKA DHE SIGURIA

-- PROCEDURA PER SHTIMIN E SHITJEVE
CREATE OR REPLACE PROCEDURE shto_transaksion_shitje (
    p_produkti IN VARCHAR2,
    p_shuma IN NUMBER,
    p_user IN VARCHAR2
) AS
BEGIN
    -- Kontrolli i sigurise
    IF p_shuma <= 0 THEN
        INSERT INTO Audit_Log (mesazhi) 
        VALUES ('Tentative e bllokuar: ' || p_produkti || ' nga ' || p_user);
        COMMIT;
        RAISE_APPLICATION_ERROR(-20001, 'Vlera duhet te jete pozitive!');
    END IF;

    -- INSERT-i kryesor
    INSERT INTO Shitjet (produkti, shuma, perdoruesi) 
    VALUES (p_produkti, p_shuma, p_user);

    -- Log suksesin
    INSERT INTO Audit_Log (mesazhi) 
    VALUES ('Sukses: ' || p_produkti || ' u shtua nga ' || p_user);
    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('Transaksioni deshtoi dhe u be Rollback.');
        RAISE;
END;
/

-- PROCEDURA PER FSHIRJEN E SIGURT TE SHITJEVE
CREATE OR REPLACE PROCEDURE fshi_transaksion_shitje (
    p_id_shitje IN NUMBER,
    p_user      IN VARCHAR2
) AS
    v_count NUMBER;
BEGIN
    -- Kontrollo nëse ekziston ID e shitjes
    SELECT COUNT(*) 
    INTO v_count
    FROM Shitjet
    WHERE id_shitje = p_id_shitje;

    IF v_count = 0 THEN
        INSERT INTO Audit_Log (mesazhi)
        VALUES ('Tentative e deshtuar per fshirje: ID ' || p_id_shitje || ' nga ' || p_user);
        COMMIT;
        RAISE_APPLICATION_ERROR(-20002, 'Shitja me ID ' || p_id_shitje || ' nuk ekziston!');
    END IF;

    -- Fshi shitjen
    DELETE FROM Shitjet
    WHERE id_shitje = p_id_shitje;

    -- Log suksesin
    INSERT INTO Audit_Log (mesazhi)
    VALUES ('Sukses: Shitja me ID ' || p_id_shitje || ' u fshi nga ' || p_user);
    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        INSERT INTO Audit_Log (mesazhi)
        VALUES ('Gabim gjate fshirjes se ID ' || p_id_shitje || ' nga ' || p_user);
        COMMIT;
        RAISE;
END;
